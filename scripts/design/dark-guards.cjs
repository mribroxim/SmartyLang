// Generate guarded, unlayered dark-mode fallbacks from the `@layer base` block in src/index.css.
// The layered fallbacks lose to Tailwind utilities, so `bg-white` / `text-zinc-900` without a
// `dark:` twin stay light-mode in dark mode. The guarded copies only apply when the element has
// no explicit dark: class of that kind (and is not marked dark-keep, nor inside a .light-zone
// such as Smarty's room, which is a drawing and stays as drawn).
const fs = require('fs');
const p = 'src/index.css';
let css = fs.readFileSync(p, 'utf8');
const START = '/* @generated dark-guards:start */';
const END = '/* @generated dark-guards:end */';
css = css.replace(new RegExp(`\\n?${START.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&')}[\\s\\S]*?${END.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&')}\\n?`), '\n');

const baseStart = css.indexOf('@layer base {', css.indexOf('DARK MODE'));
// find matching closing brace of the @layer block
let depth = 0, i = css.indexOf('{', baseStart), end = -1;
for (; i < css.length; i++) {
  if (css[i] === '{') depth++;
  else if (css[i] === '}') { depth--; if (depth === 0) { end = i; break; } }
}
const block = css.slice(css.indexOf('{', baseStart) + 1, end).replace(/\/\*[\s\S]*?\*\//g, '');
const rules = [];
const re = /([^{}]+)\{([^{}]+)\}/g;
let m;
while ((m = re.exec(block))) {
  const sels = m[1].split(',').map((s) => s.trim()).filter(Boolean);
  const decl = m[2].trim();
  const out = [];
  for (const sel of sels) {
    const mm = sel.match(/^\.dark (\.[^\s>]+)$/);
    if (!mm) continue; // skip html.dark, descendants, divide, placeholders, etc.
    const cls = mm[1];
    const raw = cls.slice(1).replace(/\\/g, '');
    let guard = null;
    if (/^hover:bg-/.test(raw)) guard = 'dark:hover:bg-';
    else if (/^bg-/.test(raw)) guard = 'dark:bg-';
    else if (/^text-/.test(raw)) guard = 'dark:text-';
    else if (/^border-/.test(raw)) guard = 'dark:border-';
    if (!guard) continue; // shadows etc. stay as they are
    out.push(`html.dark ${cls}:not([class*="${guard}"]):not(.dark-keep):not(.light-zone *)`);
  }
  if (out.length) rules.push(`${out.join(',\n')} { ${decl} }`);
}
const gen = `\n${START}\n/* Guarded dark fallbacks (generated by scripts/design/dark-guards.cjs from the @layer base block above). */\n${rules.join('\n')}\n${END}\n`;
css = css.slice(0, end + 1) + gen + css.slice(end + 1);
fs.writeFileSync(p, css);
console.log('rules', rules.length);
