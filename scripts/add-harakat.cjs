// Regex for Arabic word characters
const ARABIC_WORD_RE = /[\u0600-\u06FF\u0750-\u077F\u08A0-\u08FF\uFB50-\uFDFF\uFE70-\uFEFF]+/gu;
// Regex for diacritics
const DIACRITICS_RE = /[\u0610-\u061A\u064B-\u065F\u0670\u06D6-\u06ED\u08D3-\u08E1\u08E3-\u08FF\u0640]/gu;

function stripDiacritics(text) {
  return text.replace(DIACRITICS_RE, '');
}

function vocalizeWord(word) {
  const stripped = stripDiacritics(word);
  // direct lookup
  if (BASE_MAP[stripped]) return BASE_MAP[stripped];
  if (BASE_MAP[word]) return BASE_MAP[word];
  
  // Handle words with و prefix (and)
  if (stripped.startsWith('و') && stripped.length > 2) {
    const rest = stripped.slice(1);
    if (BASE_MAP[rest]) return 'وَ' + BASE_MAP[rest];
    // Handle و + ال
    if (rest.startsWith('ال') && rest.length > 3) {
      const inner = rest.slice(2);
      const alVocalized = BASE_MAP['ال' + inner] || BASE_MAP[inner];
      if (alVocalized) return 'وَ' + alVocalized;
    }
  }
  
  // Handle ال prefix separately when not in map
  if (stripped.startsWith('ال') && stripped.length > 3) {
    const inner = stripped.slice(2);
    if (BASE_MAP[inner]) {
      const v = BASE_MAP[inner];
      // Add ال prefix vocalization - check if inner starts with sun letter
      const sunLetters = 'تثدذرزسشصضطظلن';
      const firstInner = inner[0];
      if (sunLetters.includes(firstInner)) {
        return 'اَلْـ'.replace('لْـ', 'ل') + v; // simplified
      }
      return v; // already has ال in the vocalized form if it's in BASE_MAP
    }
  }
  
  // Handle ب prefix
  if (stripped.startsWith('ب') && stripped.length > 2) {
    const rest = stripped.slice(1);
    if (BASE_MAP[rest]) return 'بِ' + BASE_MAP[rest];
    if (rest.startsWith('ال') && rest.length > 3) {
      const inner = rest.slice(2);
      const alForm = 'ال' + inner;
      if (BASE_MAP[alForm]) return 'بِ' + BASE_MAP[alForm];
      if (BASE_MAP[inner]) return 'بِالْ' + stripDiacritics(BASE_MAP[inner]).slice(2); // rough
    }
  }
  
  // Handle ل prefix
  if (stripped.startsWith('ل') && stripped.length > 2) {
    const rest = stripped.slice(1);
    if (BASE_MAP[rest]) return 'لِ' + BASE_MAP[rest];
  }
  
  return word; // return unchanged if not found
}

function vocalizeText(text) {
  if (!text || typeof text !== 'string') return text;
  return text.replace(ARABIC_WORD_RE, (match) => vocalizeWord(match));
}

function vocalizeObject(obj) {
  if (typeof obj === 'string') return vocalizeText(obj);
  if (Array.isArray(obj)) return obj.map(vocalizeObject);
  if (obj && typeof obj === 'object') {
    const result = {};
    for (const [key, val] of Object.entries(obj)) {
      result[key] = vocalizeObject(val);
    }
    return result;
  }
  return obj;
}

const BASE_DIR = path.join(__dirname, '..', 'public', 'data', 'lang-packs', 'ar');

const FILES = [
  'comprehensive-reading.json',
  'speaking-topics.json',
  'writing-topics.json',
  'task2.json',
  'level-texts.json',
];

for (const filename of FILES) {
  const filepath = path.join(BASE_DIR, filename);
  if (!fs.existsSync(filepath)) {
    console.log(`Skipping missing file: ${filename}`);
    continue;
  }
  
  const raw = fs.readFileSync(filepath, 'utf8');
  let data;
  try {
    data = JSON.parse(raw);
  } catch(e) {
    console.error(`Error parsing ${filename}:`, e.message);
    continue;
  }
  
  const vocalized = vocalizeObject(data);
  fs.writeFileSync(filepath, JSON.stringify(vocalized, null, 2) + '\n', 'utf8');
  console.log(`Updated: ${filename}`);
}

