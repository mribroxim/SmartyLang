// Strip any existing diacritics before looking up
const DIACRITICS_RE = /[\u0610-\u061A\u064B-\u065F\u0670\u06D6-\u06ED\u08D3-\u08E1\u08E3-\u08FF\u0640]/gu;

function stripDiacritics(text) {
  return text.replace(DIACRITICS_RE, '');
}

function vocalizeWord(word) {
  // Try with current form first
  const stripped = stripDiacritics(word);
  if (WORD_MAP[stripped]) return WORD_MAP[stripped];
  // try original (may have partial diacritics already)
  if (WORD_MAP[word]) return WORD_MAP[word];
  return word; // return unchanged if not in map
}

function vocalizeText(text) {
  if (!text || typeof text !== 'string') return text;
  
  // Split on word boundaries while preserving punctuation and spaces
  // Arabic word: sequence of Arabic letters + possible diacritics + possible attached particles
  return text.replace(/[^\s\p{P}،؟!.،؛:()「」《》【】{}[\]""'']+/gu, (match) => {
    return vocalizeWord(match);
  });
}

function vocalizeObject(obj) {
  if (typeof obj === 'string') {
    return vocalizeText(obj);
  }
  if (Array.isArray(obj)) {
    return obj.map(vocalizeObject);
  }
  if (obj && typeof obj === 'object') {
    const result = {};
    for (const [key, val] of Object.entries(obj)) {
      result[key] = vocalizeObject(val);
    }
    return result;
  }
  return obj;
}

