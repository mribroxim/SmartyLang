#!/usr/bin/env node
/**
 * One-off port of the approved sticker board (design/sticker-board/*) into the app.
 *   node scripts/port-stickers.mjs
 * Writes (committed output, maintained by hand afterwards if needed):
 *   src/components/stickers/kit/kit.ts      drawing kit (all top-level names exported)
 *   src/components/stickers/sets/{core,a,b,c,sig}.ts   lazy sticker chunks
 *   src/components/stickers/manifest.ts     StickerId union + metadata (eager, tiny)
 *   src/styles/stickers.css                 keyframes + .a-* classes, all prefixed `se-`
 * Renames so nothing collides with the app: keyframes `se-*`, ids `#se-ink/#se-fuzz/#se-shade/#se-clip*`,
 * CSS vars `--se-paper`, `--se-fx-soft`. Removes the board's load-time DOM side effects.
 */
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const acorn = require('acorn');

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const BOARD = path.join(ROOT, 'design/sticker-board');
const OUT = path.join(ROOT, 'src/components/stickers');
const read = (f) => fs.readFileSync(path.join(BOARD, f), 'utf8');

const html = read('smarty-stickers.html');
const kit2Src = read('kit2.js');
const sigSrc = read('set-sig.js');

/* ── 1. Split sources ─────────────────────────────────────────── */
const scriptStart = html.indexOf('/* ═════════ Drawing kit');
const stickersMark = html.indexOf('/* ═════════ The stickers ═════════ */');
const scriptEnd = html.indexOf('</script>', stickersMark);
const htmlKit = html.slice(scriptStart, stickersMark);
let coreBody = html.slice(stickersMark, scriptEnd)
  .replace(/^const S = \[\];\s*$/m, '')
  .replace(/^const add = .*$/m, '');

// kit2: drop style injection (moved to CSS), defs injection (moved to StickerDefs), add2 (registry).
const kf2Start = kit2Src.indexOf('const KF2 = `');
const iifeEnd = kit2Src.indexOf('})();', kit2Src.indexOf('(() => {')) + '})();'.length;
const kit2Header = kit2Src.slice(kf2Start, iifeEnd);
let kit2 = kit2Src.slice(0, kf2Start) + kit2Src.slice(iifeEnd);
kit2 = kit2
  .replace(/^document\.body\.insertAdjacentHTML\(.*$/m, '')
  .replace(/^const defOnce = .*$/m, "const defOnce = (_m) => ''; // clip paths live in <StickerDefs/>")
  .replace(/^const add2 = .*$/m, '');

// set-sig: kit part (kf & friends) + stickers.
const sigSplit = sigSrc.indexOf('/* — 226');
let sigKit = sigSrc.slice(0, sigSplit);
const sigBody = sigSrc.slice(sigSplit);
sigKit = sigKit
  .replace("const _kst = document.createElement('style'); document.head.appendChild(_kst);", 'let _kst = null;')
  .replace(
    "  if (!_kseen.has(name)) { _kseen.add(name); _kst.textContent +=",
    "  name = 'se-' + name;\n  if (!_kst && typeof document !== 'undefined') { _kst = document.getElementById('se-sig-kf') || document.head.appendChild(Object.assign(document.createElement('style'), { id: 'se-sig-kf' })); }\n  if (!_kseen.has(name)) { _kseen.add(name); if (_kst) _kst.textContent +=",
  );
if (!sigKit.includes("name = 'se-' + name")) throw new Error('sig kit kf patch failed');

/* ── 2. Global renames ────────────────────────────────────────── */
function renames(code) {
  return code
    .replace(/var\(--paper\)/g, 'var(--se-paper)')
    .replace(/var\(--fx-soft\)/g, 'var(--se-fx-soft)')
    .replace(/url\(#(ink|fuzz|shade)\)/g, 'url(#se-$1)')
    .replace(/url\(#\$\{o\.filter \|\| 'ink'\}\)/g, "url(#se-${o.filter || 'ink'})")
    .replace(/(id="|url\(#)(clip(?:Peek|Bin|Dive|Globe|Sign))/g, '$1se-$2');
}

/* ── 3. Kit module with exports ───────────────────────────────── */
const kitCode = renames([htmlKit, kit2, sigKit].join('\n'));
const ast = acorn.parse(kitCode, { ecmaVersion: 'latest', sourceType: 'script' });
const names = [];
for (const node of ast.body) {
  if (node.type === 'VariableDeclaration') node.declarations.forEach((d) => d.id.type === 'Identifier' && names.push(d.id.name));
  else if (node.type === 'FunctionDeclaration') names.push(node.id.name);
}
const dupes = names.filter((n, i) => names.indexOf(n) !== i);
if (dupes.length) throw new Error('duplicate kit names: ' + dupes.join(', '));

const kitTs = `// @ts-nocheck — generated by scripts/port-stickers.mjs from design/sticker-board. Pure string builders.\n${kitCode}\nexport { ${names.join(', ')} };\n`;
fs.mkdirSync(path.join(OUT, 'kit'), { recursive: true });
fs.mkdirSync(path.join(OUT, 'sets'), { recursive: true });
fs.writeFileSync(path.join(OUT, 'kit/kit.ts'), kitTs);

/* ── 4. Set modules ───────────────────────────────────────────── */
const sets = {
  core: coreBody,
  a: read('set-a.js'),
  b: read('set-b.js'),
  c: read('set-c.js'),
  sig: sigBody,
};
const setHeader = `// @ts-nocheck — generated by scripts/port-stickers.mjs from design/sticker-board.
import { ${names.join(', ')} } from '../kit/kit';

const out = [];
const add = (name, tag, cat, svg) => { out.push({ name, tag, cat, svg }); };
const add2 = (cat, name, tag, svg) => { out.push({ name, tag, cat, svg }); };
`;
for (const [key, body] of Object.entries(sets)) {
  fs.writeFileSync(path.join(OUT, `sets/${key}.ts`), `${setHeader}\n${renames(body)}\nexport default out;\n`);
}

/* ── 5. Manifest (evaluate everything in a sandbox) ───────────── */
const fakeStyle = { textContent: '', id: '' };
let sandbox;
const baseSandbox = {
  console, Math, JSON, Array, Object, Set, Map, Number, String,
  document: { getElementById: () => null, createElement: () => ({ ...fakeStyle }), head: { appendChild: (x) => x } },
};
const entries = [];
for (const [chunk, body] of Object.entries(sets)) {
  vm.createContext(sandbox = { ...baseSandbox });
  const code = `${kitCode}\nconst out=[];const add=(name,tag,cat,svg)=>out.push({name,tag,cat,svg});const add2=(cat,name,tag,svg)=>out.push({name,tag,cat,svg});\n${renames(body)}\n;globalThis.__out = out;`;
  vm.runInContext(code, sandbox, { filename: `${chunk}.js` });
  sandbox.__out.forEach((s, i) => entries.push({ chunk, index: i, name: s.name, tag: s.tag, cat: s.cat, svg: s.svg }));
}
const slug = (s) => s.toLowerCase().replace(/[’']/g, '').replace(/&/g, 'and').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const POSTER = { 'flow.welcome-aboard': 1500, 'sig.the-magic-paw': 4300, 'sig.the-vocabulary-fish': 5600, 'sig.the-language-portal': 4900, 'sig.the-constellation-cat': 4900 };
const manifest = entries.map((e, i) => {
  const id = `${e.cat}.${slug(e.name)}`;
  // Stickers with an entrance (things appear, open, land, fill in) need a later poster frame,
  // or a frozen sticker shows an empty stage (e.g. closed curtains, cat still in the smoke).
  const intro = /a-(emerge|appear|rise|fall|zoomIn|stamp|landOn|settle|grow|growX|growY|shrinkX|fadeB|swapIn|imprint|trail|into|peek|draw)(?![\w-])/.test(e.svg());
  return { id, no: i + 1, cat: e.cat, name: e.name, tag: e.tag, chunk: e.chunk, index: e.index, posterMs: POSTER[id] ?? (intro ? 2000 : 450) };
});
const ids = manifest.map((m) => m.id);
const dupIds = ids.filter((n, i) => ids.indexOf(n) !== i);
if (dupIds.length) throw new Error('duplicate sticker ids: ' + dupIds.join(', '));

const CHUNK_KEYS = ['core', 'a', 'b', 'c', 'sig'];
const manifestTs = `// Generated by scripts/port-stickers.mjs — do not edit by hand. Kept tiny: it ships in the main bundle.
export type StickerChunk = 'core' | 'a' | 'b' | 'c' | 'sig';
export type StickerId =
${ids.map((id) => `  | '${id}'`).join('\n')};

export interface StickerMeta { id: StickerId; no: number; cat: string; chunk: StickerChunk; index: number; posterMs: number }

const CHUNKS: StickerChunk[] = ${JSON.stringify(CHUNK_KEYS)};
/** [id, chunkIndex, indexInChunk, posterMs] in board order (no = position + 1). */
const ROWS: [StickerId, number, number, number][] = ${JSON.stringify(manifest.map((m) => [m.id, CHUNK_KEYS.indexOf(m.chunk), m.index, m.posterMs]))};

export const STICKERS: readonly StickerMeta[] = ROWS.map(([id, c, index, posterMs], i) => ({
  id, no: i + 1, cat: id.slice(0, id.indexOf('.')), chunk: CHUNKS[c], index, posterMs,
}));

export const STICKER_BY_ID = Object.fromEntries(STICKERS.map((s) => [s.id, s])) as Record<StickerId, StickerMeta>;
`;
const namesTs = `// Generated by scripts/port-stickers.mjs — names + "where it's used" notes for the gallery (lazy).
import type { StickerId } from './manifest';
export const STICKER_INFO: Record<StickerId, { name: string; tag: string }> = ${JSON.stringify(Object.fromEntries(manifest.map((m) => [m.id, { name: m.name, tag: m.tag }])), null, 0)} as Record<StickerId, { name: string; tag: string }>;
`;
fs.writeFileSync(path.join(OUT, 'stickerInfo.ts'), namesTs);
fs.writeFileSync(path.join(OUT, 'manifest.ts'), manifestTs);

/* ── 6. CSS ───────────────────────────────────────────────────── */
const styleStart = html.indexOf('/* ── Sticker animation library');
const styleEnd = html.indexOf('</style>', styleStart);
const htmlCss = html.slice(styleStart, styleEnd);
const kfOf = (css) => css.match(/@keyframes [\s\S]*?\}\s*\}/g) || [];
const htmlKeyframes = kfOf(htmlCss);
const htmlClasses = htmlCss.match(/^\.a-[\w-]+ \{[^}]*\}/gm) || [];

const kit2Sandbox = {};
vm.createContext(kit2Sandbox);
vm.runInContext(`${kit2Header.replace(/\(\(\) => \{[\s\S]*\}\)\(\);/, '')}\n;globalThis.KF2=KF2;globalThis.CL2=CL2;`, kit2Sandbox);
const kit2Keyframes = kfOf(kit2Sandbox.KF2);
const kit2Classes = Object.entries(kit2Sandbox.CL2).map(([n, [d, e]]) =>
  `.a-${n} { animation: ${n} var(--d,${d}) var(--e,${e}) var(--dl,0s) infinite backwards }`);
kit2Classes.push('.a-march { animation: march var(--d,1s) linear infinite }');

const prefixKf = (k) => k.replace(/@keyframes (\w+)/, '@keyframes se-$1');
const prefixCls = (c) => '.st ' + c.replace(/animation: (\w+) /, 'animation: se-$1 ');
const css = `/* Generated by scripts/port-stickers.mjs from design/sticker-board — Smarty sticker animation library.
   Everything is scoped under .st and prefixed se- so it never collides with Tailwind (spin/pulse/bounce). */
.st { display: inline-block; position: relative; line-height: 0; vertical-align: middle; contain: layout style; color: var(--se-fx); }
.st svg { width: 100%; height: 100%; overflow: visible; display: block; }
.st * { transform-box: view-box; }
.st.off * { animation-play-state: paused !important; }
.st text { font-family: Montserrat, system-ui, sans-serif; font-weight: 800; }
.st-lite svg [filter] { filter: none; }
.st-lite svg { filter: drop-shadow(0 1px 1px rgb(0 0 0 / .25)); }

${[...htmlKeyframes, ...kit2Keyframes].map(prefixKf).join('\n')}

${[...htmlClasses, ...kit2Classes].map(prefixCls).join('\n')}
`;
fs.writeFileSync(path.join(ROOT, 'src/styles/stickers.css'), css);

console.log(`kit names: ${names.length}; stickers: ${manifest.length}; keyframes: ${htmlKeyframes.length + kit2Keyframes.length}; classes: ${htmlClasses.length + kit2Classes.length}`);
